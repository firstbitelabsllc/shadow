EOF
}

main() {
  if [ $# -lt 1 ]; then
    print_usage >&2
    exit 2
  fi

  case "$1" in
    bash)
      emit_bash
      ;;
    zsh)
      emit_zsh
      ;;
    fish)
      emit_fish
      ;;
    --help|-h|help)
      print_usage
      ;;
    *)
      echo "vidux-completion.sh: unknown shell: $1" >&2
      echo "supported: bash, zsh, fish" >&2
      print_usage >&2
      exit 2
      ;;
  esac
}

main "$@"
