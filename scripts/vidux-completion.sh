#!/usr/bin/env bash
# vidux-completion.sh — emit shell completion scripts for vidux.
#
# Usage: vidux-completion.sh <bash|zsh|fish>
#
#
# Each completion source completes the same subcommand list maintained
# in bin/vidux plus the top-level long/short flags. Keep this list in
# sync with bin/vidux's print_top_help / main() case branches.
set -euo pipefail

# Canonical subcommand list. Order matches print_top_help() in bin/vidux.
VIDUX_SUBCOMMANDS="dev browse status init drift config signpost http-smoke doctor build release completion help"
VIDUX_FLAGS="--help -h --version -v"

print_usage() {
  cat <<EOF
vidux-completion.sh — emit a shell completion script to stdout.

usage: vidux-completion.sh <bash|zsh|fish>

Each form prints a self-contained completion script. Install via:
  echo 'source <(vidux completion bash)' >> ~/.bashrc
  echo 'source <(vidux completion zsh)'  >> ~/.zshrc
  vidux completion fish > ~/.config/fish/completions/vidux.fish
EOF
}

emit_bash() {
  cat <<EOF
# vidux bash completion — generated by 'vidux completion bash'.
# Install: echo 'source <(vidux completion bash)' >> ~/.bashrc
_vidux_complete() {
  local cur prev words cword
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"

  local subcommands="${VIDUX_SUBCOMMANDS}"
  local flags="${VIDUX_FLAGS}"

  if [ "\$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=( \$(compgen -W "\${subcommands} \${flags}" -- "\${cur}") )
    return 0
  fi

  case "\${COMP_WORDS[1]}" in
    help)
      if [ "\$COMP_CWORD" -eq 2 ]; then
        COMPREPLY=( \$(compgen -W "\${subcommands}" -- "\${cur}") )
        return 0
      fi
      ;;
    completion)
      if [ "\$COMP_CWORD" -eq 2 ]; then
        COMPREPLY=( \$(compgen -W "bash zsh fish --help -h" -- "\${cur}") )
        return 0
      fi
      ;;
    dev)
      COMPREPLY=( \$(compgen -W "--bg --help -h" -- "\${cur}") )
      return 0
      ;;
    browse)
      COMPREPLY=( \$(compgen -W "--no-open --foreground -f --port --host --root --open-host --comments-path --receipt-corpus-path --help -h" -- "\${cur}") )
      return 0
      ;;
    status)
      COMPREPLY=( \$(compgen -W "--root --focus --all --json --help -h" -- "\${cur}") )
      return 0
      ;;
    config)
      if [ "\$COMP_CWORD" -eq 2 ]; then
        COMPREPLY=( \$(compgen -W "path check show init --help -h" -- "\${cur}") )
      else
        COMPREPLY=( \$(compgen -W "--config --json --strict --path --source --force --help -h" -- "\${cur}") )
      fi
      return 0
      ;;
    signpost)
      if [ "\$COMP_CWORD" -eq 2 ]; then
        COMPREPLY=( \$(compgen -W "emit summary trace wrap lifecycle-smoke spawned-subagent-smoke --help -h" -- "\${cur}") )
      else
        COMPREPLY=( \$(compgen -W "--feature --action --status --duration-ms --exit-code --called --emitter --meta --log --run-id --runtime --limit --json --help -h" -- "\${cur}") )
      fi
      return 0
      ;;
    http-smoke)
      COMPREPLY=( \$(compgen -W "--url --timeout --max-sample-bytes --json --help -h" -- "\${cur}") )
      return 0
      ;;
    *)
      COMPREPLY=( \$(compgen -W "--help -h" -- "\${cur}") )
      return 0
      ;;
  esac
}
complete -F _vidux_complete vidux
EOF
}

emit_zsh() {
  cat <<EOF
#compdef vidux
# vidux zsh completion — generated by 'vidux completion zsh'.
# Install: echo 'source <(vidux completion zsh)' >> ~/.zshrc
_vidux() {
  local -a subcommands
  subcommands=(
    'dev:Start the local dev browser (foreground; auto-restart)'
    'browse:Launch the plan browser at :7191'
    'status:Print plan status across operational PLAN.md files'
    'init:Bootstrap a new plan PLAN.md from template'
    'drift:Record planned-vs-actual drift in PLAN.md'
    'config:Inspect, validate, or initialize local vidux.config.json'
    'signpost:Emit or summarize local feature signposts'
    'http-smoke:Classify local HTTP monitor budget responses'
    'doctor:Diagnose local toolchain + auth'
    'build:Run docs:build + contract tests as release gate'
    'release:Plan/ledger-gated release tag + push'
    'completion:Emit a shell completion script (bash|zsh|fish)'
    'help:Show help for vidux or a subcommand'
  )

  _arguments -C \\
    '1: :->cmd' \\
    '*::arg:->args'

  case \$state in
    cmd)
      _describe -t commands 'vidux command' subcommands
      _values 'flag' \\
        '--help[Show top-level help]' \\
        '-h[Show top-level help]' \\
        '--version[Print vidux version]' \\
        '-v[Print vidux version]'
      ;;
    args)
      case \$line[1] in
        help)
          _describe -t commands 'subcommand' subcommands
          ;;
        completion)
          _values 'shell' \\
            'bash[Emit bash completion]' \\
            'zsh[Emit zsh completion]' \\
            'fish[Emit fish completion]'
          _values 'flag' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        dev)
          _values 'flag' \\
            '--bg[Background mode]' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        browse)
          _values 'flag' \\
            '--no-open[Do not open a browser]' \\
            '--foreground[Run in foreground]' \\
            '-f[Run in foreground]' \\
            '--port[Bind or reuse port]' \\
            '--host[Server bind host]' \\
            '--root[Scan root for PLAN.md files]' \\
            '--open-host[Browser URL host]' \\
            '--comments-path[Comments JSONL path]' \\
            '--receipt-corpus-path[Receipt corpus JSONL path]' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        status)
          _values 'flag' \\
            '--root[Root path to scan]' \\
            '--focus[Repo name to prioritize]' \\
            '--all[Include empty, shipped, and stale tracked rows]' \\
            '--json[Print JSON]' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        config)
          _values 'config command' path check show init
          _values 'flag' \\
            '--config[Explicit config path]' \\
            '--json[Print JSON]' \\
            '--strict[Require live config]' \\
            '--path[Destination path]' \\
            '--source[Source config]' \\
            '--force[Overwrite destination]' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        signpost)
          _values 'signpost command' emit summary trace wrap lifecycle-smoke spawned-subagent-smoke
          _values 'flag' \\
            '--feature[Feature name]' \\
            '--action[Action name]' \\
            '--status[Event status]' \\
            '--log[Log path]' \\
            '--run-id[Filter run id]' \\
            '--runtime[Runtime attribution]' \\
            '--limit[Limit trace rows]' \\
            '--json[Print JSON]' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        http-smoke)
          _values 'flag' \\
            '--url[URL to smoke]' \\
            '--timeout[Total budget per URL in seconds]' \\
            '--max-sample-bytes[Maximum response sample bytes]' \\
            '--json[Print JSON]' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
        *)
          _values 'flag' \\
            '--help[Show help]' \\
            '-h[Show help]'
          ;;
      esac
      ;;
  esac
}

compdef _vidux vidux
EOF
}

emit_fish() {
  cat <<'EOF'
